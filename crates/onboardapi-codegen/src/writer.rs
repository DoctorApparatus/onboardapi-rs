//! Small helpers for writing generated source files.

use std::{fmt::Write as _, path::Path};

use crate::error::Result;

/// Line-oriented source buffer with indentation.
#[derive(Default)]
pub struct Src {
    buf: String,
    indent: usize,
}

impl Src {
    pub fn line(&mut self, s: impl AsRef<str>) -> &mut Self {
        let s = s.as_ref();
        if s.is_empty() {
            self.buf.push('\n');
        } else {
            for l in s.lines() {
                let _ = writeln!(self.buf, "{:width$}{l}", "", width = self.indent * 4);
            }
        }
        self
    }

    pub fn blank(&mut self) -> &mut Self {
        self.buf.push('\n');
        self
    }

    pub fn open(&mut self, s: impl AsRef<str>) -> &mut Self {
        self.line(s);
        self.indent += 1;
        self
    }

    pub fn close(&mut self, s: impl AsRef<str>) -> &mut Self {
        self.indent -= 1;
        self.line(s)
    }

    pub fn finish(self) -> String {
        self.buf
    }
}

/// Writes only if the content changed, so cargo does not rebuild needlessly.
pub fn write_if_changed(path: &Path, content: &str) -> Result<()> {
    if std::fs::read_to_string(path).is_ok_and(|old| old == content) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, content)?;
    Ok(())
}

